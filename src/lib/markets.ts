/**
 * Expand cities per country for search + profile filters.
 * Subjects remain defined in this file.
 */
export const TOP_COUNTRIES: MarketCountry[] = TOP_COUNTRIES_BASE.map((country) => ({
  ...country,
  cities: MARKET_CITIES_BY_COUNTRY_CODE[country.code] || country.cities,
}));

/** Top 8 countries shown as cards on the homepage. */
export const HOMEPAGE_FEATURED_COUNTRY_CODES = [
  "PK",
  "IN",
  "US",
  "GB",
  "AE",
  "SA",
  "CA",
  "AU",
] as const;

const HOMEPAGE_FEATURED = new Set<string>(HOMEPAGE_FEATURED_COUNTRY_CODES);

export function allMarketSubjects() {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const country of TOP_COUNTRIES) {
    for (const subject of country.subjects) {
      if (seen.has(subject)) continue;
      seen.add(subject);
      out.push(subject);
    }
  }
  return out;
}

export function allMarketCities() {
  const seen = new Set<string>();
  const out: string[] = ["Online"];
  for (const country of TOP_COUNTRIES) {
    for (const city of country.cities) {
      if (seen.has(city)) continue;
      seen.add(city);
      out.push(city);
    }
  }
  return out;
}

export function countryByCode(code: string) {
  return TOP_COUNTRIES.find((c) => c.code === code.toUpperCase()) || null;
}

export function countryByName(name: string) {
  return TOP_COUNTRIES.find((c) => c.name.toLowerCase() === name.toLowerCase()) || null;
}

export function homepageFeaturedCountries() {
  return HOMEPAGE_FEATURED_COUNTRY_CODES.map((code) => countryByCode(code)).filter(
    (c): c is MarketCountry => c !== null,
  );
}

export function otherMarketCountries() {
  return TOP_COUNTRIES.filter((c) => !HOMEPAGE_FEATURED.has(c.code));
}

export const FEATURED_COUNTRY_LIMIT = 8;

/**
 * Exactly 8 country cards, plus the remaining markets for a dropdown.
 * If the visitor's country is not already in the 8, it replaces the last slot.
 */
export function selectFeaturedMarketCountries(pinnedName?: string | null): {
  featured: MarketCountry[];
  rest: MarketCountry[];
} {
  const seen = new Set<string>();
  const featured: MarketCountry[] = [];
  for (const country of [...homepageFeaturedCountries(), ...TOP_COUNTRIES]) {
    if (seen.has(country.code)) continue;
    seen.add(country.code);
    featured.push(country);
    if (featured.length === FEATURED_COUNTRY_LIMIT) break;
  }

  const pinned = pinnedName
    ? featured.find((c) => c.name === pinnedName) || countryByName(pinnedName)
    : null;

  if (pinned) {
    if (featured.some((c) => c.code === pinned.code)) {
      featured.splice(0, featured.length, pinned, ...featured.filter((c) => c.code !== pinned.code));
    } else {
      featured.splice(0, featured.length, pinned, ...featured.slice(0, FEATURED_COUNTRY_LIMIT - 1));
    }
  }

  const featuredCodes = new Set(featured.map((c) => c.code));
  const rest = TOP_COUNTRIES.filter((c) => !featuredCodes.has(c.code)).sort((a, b) =>
    a.name.localeCompare(b.name),
  );

  return { featured: featured.slice(0, FEATURED_COUNTRY_LIMIT), rest };
}

